-- Clubes ---------------------------------------------------------------
CREATE TABLE clubes (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(60)    NOT NULL,
    sigla     CHAR(3)        NOT NULL,
    caixa     DECIMAL(10,2)  NOT NULL DEFAULT 300.00,
    formacao  VARCHAR(5),
    criado_em TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT uk_clubes_sigla UNIQUE (sigla),
    CONSTRAINT ck_clubes_caixa CHECK (caixa >= 0),
    CONSTRAINT ck_clubes_formacao CHECK (formacao IS NULL OR formacao IN ('3-1', '2-2', '2-1-1', '1-2-1'))
);

-- RN10: nome único ignorando maiúsculas/minúsculas, mas considerando acentos
CREATE UNIQUE INDEX uk_clubes_nome_lower ON clubes (lower(nome));

-- Jogadores ------------------------------------------------------------
CREATE TABLE jogadores (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100)  NOT NULL,
    posicao       VARCHAR(3)    NOT NULL,
    agilidade     INTEGER       NOT NULL,
    idade         INTEGER       NOT NULL,
    valor_base    DECIMAL(6,2)  NOT NULL,
    condicao      VARCHAR(20)   NOT NULL DEFAULT 'APTO',
    clube_id      INTEGER       REFERENCES clubes (id),
    velocidade    INTEGER       NOT NULL,
    finalizacao   INTEGER       NOT NULL,
    passe         INTEGER       NOT NULL,
    drible        INTEGER       NOT NULL,
    defesa        INTEGER       NOT NULL,
    fisico        INTEGER       NOT NULL,
    potencial     INTEGER       NOT NULL,
    excluido_em   TIMESTAMP,
    criado_em     TIMESTAMP     NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_jogadores_posicao   CHECK (posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA')),
    CONSTRAINT ck_jogadores_condicao  CHECK (condicao IN ('APTO', 'MAL_CONDICIONADO', 'DOENTE')),
    CONSTRAINT ck_jogadores_agilidade CHECK (agilidade BETWEEN 1 AND 100),
    CONSTRAINT ck_jogadores_idade     CHECK (idade BETWEEN 16 AND 45),
    CONSTRAINT ck_jogadores_valor     CHECK (valor_base >= 1.00),
    CONSTRAINT ck_jogadores_atributos CHECK (
        velocidade  BETWEEN 1 AND 99 AND finalizacao BETWEEN 1 AND 99 AND
        passe       BETWEEN 1 AND 99 AND drible      BETWEEN 1 AND 99 AND
        defesa      BETWEEN 1 AND 99 AND fisico      BETWEEN 1 AND 99 AND
        potencial   BETWEEN 1 AND 99
    )
);

CREATE INDEX ix_jogadores_clube ON jogadores (clube_id);
CREATE INDEX ix_jogadores_ativos ON jogadores (nome) WHERE excluido_em IS NULL;

-- Contratos ------------------------------------------------------------
CREATE TABLE contratos (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jogador_id     INTEGER       NOT NULL REFERENCES jogadores (id),
    clube_id       INTEGER       NOT NULL REFERENCES clubes (id),
    valor_compra   DECIMAL(6,2)  NOT NULL,
    fidelidade_ate TIMESTAMP     NOT NULL,
    situacao       VARCHAR(12)   NOT NULL DEFAULT 'ATIVO',
    iniciado_em    TIMESTAMP     NOT NULL,
    encerrado_em   TIMESTAMP,
    CONSTRAINT ck_contratos_situacao CHECK (situacao IN ('ATIVO', 'ENCERRADO', 'RESCINDIDO'))
);

-- um jogador só pode ter um contrato ATIVO
CREATE UNIQUE INDEX uk_contratos_ativo_por_jogador ON contratos (jogador_id) WHERE situacao = 'ATIVO';
CREATE INDEX ix_contratos_clube ON contratos (clube_id);

-- Transações -----------------------------------------------------------
CREATE TABLE transacoes (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clube_id       INTEGER       NOT NULL REFERENCES clubes (id),
    jogador_id     INTEGER       NOT NULL REFERENCES jogadores (id),
    nome_jogador   VARCHAR(100)  NOT NULL,
    tipo           VARCHAR(6)    NOT NULL,
    valor          DECIMAL(6,2)  NOT NULL,
    taxa           DECIMAL(6,2)  NOT NULL,
    multa          DECIMAL(6,2)  NOT NULL DEFAULT 0.00,
    lucro          DECIMAL(7,2),
    variacao_caixa DECIMAL(8,2)  NOT NULL,
    criado_em      TIMESTAMP     NOT NULL,
    CONSTRAINT ck_transacoes_tipo CHECK (tipo IN ('COMPRA', 'VENDA'))
);

CREATE INDEX ix_transacoes_clube_data ON transacoes (clube_id, criado_em DESC, id DESC);
CREATE INDEX ix_transacoes_jogador ON transacoes (jogador_id);

-- Escalações -----------------------------------------------------------
CREATE TABLE escalacoes (
    clube_id   INTEGER   NOT NULL REFERENCES clubes (id),
    jogador_id INTEGER   NOT NULL REFERENCES jogadores (id),
    criado_em  TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (clube_id, jogador_id),
    CONSTRAINT uk_escalacoes_jogador UNIQUE (jogador_id)
);

-- Partidas -------------------------------------------------------------
CREATE TABLE partidas (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandante_id         INTEGER     NOT NULL REFERENCES clubes (id),
    visitante_id        INTEGER     NOT NULL REFERENCES clubes (id),
    gols_mandante       INTEGER     NOT NULL,
    gols_visitante      INTEGER     NOT NULL,
    formacao_mandante   VARCHAR(5)  NOT NULL,
    formacao_visitante  VARCHAR(5)  NOT NULL,
    jogada_em           TIMESTAMP   NOT NULL,
    CONSTRAINT ck_partidas_clubes  CHECK (mandante_id <> visitante_id),
    CONSTRAINT ck_partidas_gols    CHECK (gols_mandante BETWEEN 0 AND 3 AND gols_visitante BETWEEN 0 AND 3)
);

CREATE INDEX ix_partidas_mandante ON partidas (mandante_id);
CREATE INDEX ix_partidas_visitante ON partidas (visitante_id);

-- Duelos ---------------------------------------------------------------
CREATE TABLE duelos_partida (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id         INTEGER      NOT NULL REFERENCES partidas (id),
    ordem              INTEGER      NOT NULL,
    clube_atacante_id  INTEGER      NOT NULL REFERENCES clubes (id),
    atacante_id        INTEGER      NOT NULL REFERENCES jogadores (id),
    defensor_id        INTEGER      NOT NULL REFERENCES jogadores (id),
    nome_atacante      VARCHAR(100) NOT NULL,
    nome_defensor      VARCHAR(100) NOT NULL,
    posicao_atacante   VARCHAR(3)   NOT NULL,
    posicao_defensor   VARCHAR(3)   NOT NULL,
    condicao_atacante  VARCHAR(20)  NOT NULL,
    condicao_defensor  VARCHAR(20)  NOT NULL,
    atributo_ataque    VARCHAR(10)  NOT NULL,
    atributo_defesa    VARCHAR(10)  NOT NULL,
    valor_ataque       INTEGER      NOT NULL,
    valor_defesa       INTEGER      NOT NULL,
    gol                BOOLEAN      NOT NULL,
    CONSTRAINT uk_duelos_partida_ordem UNIQUE (partida_id, ordem),
    CONSTRAINT ck_duelos_ordem CHECK (ordem BETWEEN 1 AND 6)
);